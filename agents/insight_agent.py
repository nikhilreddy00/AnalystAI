"""
Insight Delivery Agent: the executive story of one analysis, on the agent contract
(docs/agent-contract.md): INSIGHT_CARD, prompts/insight/v<N>.md, build_context, `llm` as a
parameter.

The model writes only what needs judgment: a headline that answers the question, a short
summary, the key findings and the actions they support, each citing Evidence ids, plus a few
caveats and follow-up questions. Code does the rest:
- build_context: the question, computed data facts (rows, date range, the months a MoM figure
  compares), the evidence, the cleaning summary, chart titles and scoped earlier analyses; all
  data-derived text is masked and delimited. The ingestion summary is left out: it is a model's
  paraphrase of five rows (it called 12 months of data "November 2025").
- hard rules, held by repair: unknown evidence ids are dropped; a sentence with a number or a
  date that isn't in what the model was shown, or with statistical jargon, is removed; a finding
  or action that cites no evidence is removed; a claim left empty is rewritten from its evidence.
- the analyst view and the data-quality alerts are built from the Evidence and the cleaning
  audit. The model's version of them invented methods (e.g. "deduplicated on full-row equality").
"""
