# ── Context ────────────────────────────────────────────────────────────────────

class InsightContext(BaseModel):
    question: str
    facts: str        # computed by code: rows, columns, the date range (names a column)
    evidence: str     # one line per Evidence item; claims carry column and group names
    quality: str      # the cleaning summary (names columns)
    charts: str       # chart titles (carry group names) and the evidence each shows
    display: str      # raw column name → display name
    memory: str       # earlier analyses: earlier model output derived from data
    first: tuple[int, int] | None = None   # (year, month) of the data's range, or None
    last: tuple[int, int] | None = None

    def render(self) -> str:
        return "\n\n".join(filter(bool, [
            f"User's question: {self.question}",
            "Data facts (computed):\n" + delimit_untrusted(self.facts),
            "Evidence (cite these ids):\n" + delimit_untrusted(self.evidence)
            if self.evidence else "Evidence: none was computed.",
            "Data quality:\n" + delimit_untrusted(self.quality) if self.quality else "",
            "Charts shown with this report:\n" + delimit_untrusted(self.charts) if self.charts else "",
            "Column display names (use these):\n" + delimit_untrusted(self.display)
            if self.display else "",
            "Earlier analyses of this dataset (may be outdated; not evidence):\n"
            + delimit_untrusted(self.memory) if self.memory else "",
        ]))

    def pool(self) -> list:
        """Where a number in the report may come from: what the model was shown, minus the
        question and the earlier analyses."""
        return [self.facts, self.evidence, self.quality, self.charts, _CONVENTIONS]


def _month(ym: tuple[int, int]) -> str:
    return date(ym[0], ym[1], 1).strftime("%b %Y")


def _date_span(session: AnalysisSession) -> tuple[str, list] | None:
    audit, contract = session.cleaning_audit, session.data_contract
    ranges = audit.date_ranges if audit else {}
    order = [c for c in (contract.date_columns if contract else []) if c in ranges] + list(ranges)
    return (order[0], ranges[order[0]]) if order else None


def build_context(session: AnalysisSession, past: list[str] | None = None) -> InsightContext:
    findings, audit, contract = session.analysis_findings, session.cleaning_audit, session.data_contract
    narrative = session.narrative
    evidence = list(findings.evidence if findings else [])[:_MAX_EVIDENCE]

    facts: list[str] = []
    if audit:
        facts.append(f"{audit.rows_after:,} rows after cleaning ({audit.rows_before:,} before).")
    elif contract:
        facts.append(f"{contract.row_count:,} rows.")
    if contract:
        facts.append(f"{contract.column_count} columns.")
    if narrative:
        facts.append(f"One row is one {narrative.entity_singular}.")
    first = last = None
    months = 0
    if span := _date_span(session):
        col, (lo, hi, months) = span
        first, last = (int(lo[:4]), int(lo[5:7])), (int(hi[:4]), int(hi[5:7]))
        facts.append(f"Date range ({col}): {lo} to {hi}, {months} month{'s' * (months != 1)}.")
        if months > 1:
            prev = (last[0], last[1] - 1) if last[1] > 1 else (last[0] - 1, 12)
            facts.append(f"Month-over-month figures compare {_month(last)} with {_month(prev)}.")
        else:
            facts.append("There is one month of data: no month-over-month comparison exists.")
    else:
        facts.append("There is no date column: name no period.")

    chart_of: dict[str, str] = {}
    chart_lines = []
    for c in session.chart_configs:
        if c.placement != "summary":
            continue
        ids = c.rationale.evidence_ids if c.rationale else []
        for i in ids:
            chart_of.setdefault(i, c.title)
        chart_lines.append(f"- {mask_pii(c.title)}" + (f" (shows {', '.join(ids)})" if ids else ""))

    lines = []
    for e in evidence:
        line = (f"- [{e.id}] {e.claim} | rows: {e.row_count:,} | confidence: {e.confidence} "
                f"({e.confidence_reason})")
        if e.kind == "trend" and e.id.endswith(":YoY") and 0 < months < 13:
            line += (f" | caution: the data covers {months} months, so this compares partial "
                     "years; do not report it as a year-over-year change")
        if e.kind != "cleaning":
            line += f" | values: {e.result_excerpt[:300]}"
        if e.assumptions:
            line += f" | notes: {'; '.join(e.assumptions[:3])}"
        lines.append(str(mask_pii(line)))

    names = narrative.column_display_names if narrative else {}
    display = "\n".join(f"{raw} → {shown}" for raw, shown in list(names.items())[:60]
                        if raw.lower() != shown.lower())
    return InsightContext(
        question=session.task_plan.raw_query if session.task_plan else "",
        facts="\n".join(facts), evidence="\n".join(lines),
        quality=str(mask_pii(audit.summary)) if audit else "", charts="\n".join(chart_lines),
        display=display, memory="\n".join(f"- {mask_pii(p)}" for p in (past or [])[:3]),
        first=first, last=last)


# ── Agent ──────────────────────────────────────────────────────────────────────

async def run_insight_agent(session: AnalysisSession, llm: LLMClient,
                            similar_past_insights: list[str] | None = None) -> InsightReport:
    """The InsightReport for the session's findings. `similar_past_insights` are the scoped
    earlier analyses the orchestrator retrieved (memory/vector_store.py)."""
    if session.analysis_findings is None:
        raise ValueError("AnalysisFindings must be present before insight generation.")
    ctx = build_context(session, similar_past_insights)
    data = await _ask(ctx, llm)
    if data is None:
        # Unparseable twice: a report built from the evidence alone. Typed LLM errors
        # (refusal, truncation, outage) propagate from llm.complete.
        trace_verdict("insight", PROMPT_VERSION, "unparseable")
        data = {}
    return _assemble(session, ctx, data)


async def _ask(ctx: InsightContext, llm: LLMClient) -> dict | None:
    messages = [{"role": "user", "content": ctx.render()}]
    for _ in range(2):
        result = await llm.complete(agent="insight", prompt_version=PROMPT_VERSION,
                                    max_tokens=2000, system=_SYSTEM, messages=messages)
        try:
            data = json.loads(strip_markdown_fences(result.text.strip()))
            if isinstance(data, dict):
                return data
        except json.JSONDecodeError:
            pass
        messages = messages + [
            {"role": "assistant", "content": result.text.strip() or "(empty)"},
            {"role": "user", "content": "That was not a valid JSON object. Return ONLY the JSON "
                                        "object described in the instructions."}]
    return None


def _assemble(session: AnalysisSession, ctx: InsightContext, data: dict) -> InsightReport:
    findings = session.analysis_findings
    narrative = session.narrative
    evidence = {e.id: e for e in findings.evidence}
    pool, has_dates = ctx.pool(), ctx.first is not None
    removed = {"sentences": 0, "uncited": 0}

    def ok(sentence: str, executive: bool) -> bool:
        bad = (ungrounded_numbers(without_dates(sentence, has_dates), pool)
               or ungrounded_dates(sentence, ctx.first, ctx.last)
               or (executive and executive_jargon(sentence)))
        removed["sentences"] += bool(bad)
        return not bad

    def fix(text, executive: bool = True) -> str:
        text = _clean_for_executive(str(text or ""), narrative) if executive else str(text or "")
        return " ".join(s for s in _SENTENCE_RE.split(text.strip()) if s.strip() and ok(s, executive))

    def cited(item) -> list[str]:
        raw = item.get("evidence") if isinstance(item, dict) else None
        return list(dict.fromkeys(i for i in (raw or []) if isinstance(i, str) and i in evidence))

    def items(key: str) -> list:
        v = data.get(key)
        return v if isinstance(v, list) else []

    head = data.get("headline")
    head_ids = cited(head)
    headline = fix(head.get("text") if isinstance(head, dict) else head)
    summary = [Claim(text=t, evidence_ids=cited(s)) for s in items("summary")[:3]
               if (t := fix(s.get("text") if isinstance(s, dict) else s))]

    claims: list[Claim] = []
    for f in items("findings")[:5]:
        ids = cited(f)
        if not ids:
            removed["uncited"] += 1
            continue
        text = fix(f.get("text")) or _plain(evidence[ids[0]], findings, narrative)
        claims.append(Claim(text=text, evidence_ids=ids))
    actions: list[ActionItem] = []
    for a in items("actions")[:3]:
        ids = cited(a)
        if not ids:
            removed["uncited"] += 1
            continue
        if action := fix(a.get("action")):
            actions.append(ActionItem(action=action, expected_impact=fix(a.get("impact")),
                                      evidence_ids=ids))
    if not claims:   # nothing the model wrote survived: the evidence, said plainly
        claims = [Claim(text=_plain(e, findings, narrative), evidence_ids=[e.id])
                  for e in findings.evidence if e.kind != "cleaning"][:5]
    if not headline:
        headline, head_ids = (claims[0].text, claims[0].evidence_ids) if claims else (
            "No result answers this question yet.", [])
    questions = [q for q in (fix(q) for q in items("questions")[:3] if isinstance(q, str)) if q]
    caveats = [c for c in (fix(c, executive=False) for c in items("caveats")[:3]
                           if isinstance(c, str)) if c]

    if removed["sentences"]:
        trace_verdict("insight", PROMPT_VERSION, "grounding_rewritten")
    if removed["uncited"]:
        trace_verdict("insight", PROMPT_VERSION, "uncited_dropped")
    if not data:
        caveats.append("The written summary could not be generated; the findings above are the "
                       "computed results, stated plainly.")
    if removed["sentences"] or removed["uncited"]:
        caveats.append(f"{removed['sentences']} sentence(s) stating a number, date or term not "
                       f"in the evidence and {removed['uncited']} uncited claim(s) were removed.")

    executive = ExecutiveSummary(headline=headline, headline_evidence_ids=head_ids,
                                 paragraphs=summary, findings=claims, action_items=actions)
    analyst = _analyst_view(session, caveats)
    alerts, overflow = _alerts(session)
    return InsightReport(
        executive_summary=_flatten_executive_to_text(executive),
        technical_findings=list(analyst.statistical_notes),
        recommended_actions=[RecommendedAction(priority=i + 1, action=a.action,
                                               reasoning=a.expected_impact,
                                               metric_impact=a.expected_impact or None)
                             for i, a in enumerate(actions)],
        anomaly_alerts=alerts,
        proactive_questions=questions,
        methodology_notes=analyst.methodology,
        executive_view=executive,
        analyst_view=analyst,
        additional_issues_note=overflow,
    )


# ── Deterministic parts: plain claims, the analyst view, the alerts ────────────

def _name(col: str, narrative: DataNarrative | None) -> str:
    return _clean_for_executive(col, narrative)


def _label(value) -> str:
    """A group name from the data. A long one may be an instruction, so it isn't repeated."""
    text = str(mask_pii(str(value)))
    return text if len(text) <= 30 else "another group"


def _plain(e: Evidence, findings, narrative: DataNarrative | None) -> str:
    """One plain sentence from an Evidence item's computed values, for a claim the repair
    emptied. Every number in it is in the evidence."""
    text = e.claim
    if e.kind == "trend":
        t = next((t for t in findings.trends if e.id == f"trend:{t.column}"   # build_evidence's id
                  + (f" ({t.segment})" if t.segment else "") + f":{t.period}"), None)
        if t:
            seg = f" for {_label(t.segment)}" if t.segment else ""
            way = "rose" if t.pct_change > 0 else "fell" if t.pct_change < 0 else "was flat"
            period = "month over month" if t.period == "MoM" else "year over year"
            text = f"{_name(t.column, narrative)}{seg} {way} {abs(t.pct_change):.1f}% {period}."
    elif e.kind == "segment":
        s = next((s for s in findings.segments
                  if segment_id(s.segment_column, s.metric_column, s.aggregation) == e.id), None)
        vals = [r for r in (s.results if s else []) if isinstance(r.get("value"), (int, float))]
        if vals:
            hi = max(vals, key=lambda r: r["value"])
            lo = min(vals, key=lambda r: r["value"])
            what = {"mean": "Average", "sum": "Total", "count": "Number of rows for"}.get(
                s.aggregation, s.aggregation.title())
            text = (f"{what} {_name(s.metric_column, narrative)} by "
                    f"{_name(s.segment_column.replace('|', ' and '), narrative)}: "
                    f"{_label(hi.get('name'))} highest ({hi['value']:,.2f}), "
                    f"{_label(lo.get('name'))} lowest ({lo['value']:,.2f}).")
    elif e.kind == "correlation":
        a, _, b = e.id.removeprefix("corr:").partition("__")
        r = findings.correlations.get(f"{a}__{b}", 0.0)
        how = ("tend to move together" if r >= 0.3 else "tend to move in opposite directions"
               if r <= -0.3 else "show little relationship")
        text = f"{_name(a, narrative).capitalize()} and {_name(b, narrative)} {how}."
    elif e.kind == "anomaly":
        col = e.id.removeprefix("anom:")
        n = sum(a.column == col for a in findings.anomalies)
        text = f"{n} unusual {_name(col, narrative)} values were flagged and kept."
    elif e.kind == "test":
        t = findings.statistical_tests[int(e.id.removeprefix("test:"))] \
            if e.id.removeprefix("test:").isdigit() else None
        if t and t.p_value is not None:
            text = ("The difference could be chance." if t.p_value >= 0.05
                    else "The difference is unlikely to be chance.")
    elif e.kind == "eda":
        col = e.id.removeprefix("eda:")
        st = findings.eda_summary.get(col, {})
        if isinstance(st.get("median"), (int, float)) and isinstance(st.get("mean"), (int, float)):
            text = (f"A typical {_name(col, narrative)} value is {st['median']:,.2f}; "
                    f"the average is {st['mean']:,.2f}.")
    text = _clean_for_executive(text, narrative)
    if e.confidence == "low":
        text += f" This result is uncertain ({e.confidence_reason})."
    return text


def _analyst_view(session: AnalysisSession, model_caveats: list[str]) -> AnalystDetail:
    audit, findings = session.cleaning_audit, session.analysis_findings
    evidence = findings.evidence
    kinds = sorted({e.kind for e in evidence} - {"cleaning"})
    note = audit.anomaly_report.methodology_note if audit and audit.anomaly_report else ""
    methodology = " ".join(filter(None, [
        f"Cleaning ({CLEANING_CARD.name} {CLEANING_CARD.version}): {audit.summary}" if audit else "",
        f"Analysis ({ANALYSIS_CARD.name} {ANALYSIS_CARD.version}) computed: {', '.join(kinds)}."
        if kinds else "",
        *ANALYSIS_CARD.limits[:2], note]))
    notes = [f"{e.claim} (n = {e.row_count:,}; {e.confidence} confidence: {e.confidence_reason})"
             for e in evidence if e.kind != "cleaning"]
    low = [f"{e.claim}: low confidence ({e.confidence_reason})" for e in evidence
           if e.confidence == "low"]
    assumptions = [a for e in evidence for a in e.assumptions]
    caveats = list(dict.fromkeys([*model_caveats, *low, *assumptions]))[:12]
    code = [c.rationale.code for c in session.chart_configs if c.rationale and c.rationale.code]
    return AnalystDetail(methodology=methodology, statistical_notes=notes, caveats=caveats,
                         code_references=list(dict.fromkeys(code))[:3])


def _pct(p: float) -> str:
    """The audit rounds to 0.1, so 2999 of 3000 missing is stored as 100.0. An alerted column
    still has values (an empty one is skipped at triage): '>99.9%', as the cleaning agent says."""
    return ">99.9%" if p >= 99.9 else f"{p:.1f}%"


def _alerts(session: AnalysisSession) -> tuple[list[AnomalyAlert], str]:
    """Data-quality alerts from the cleaning audit, severity by the numeric triggers."""
    audit, narrative = session.cleaning_audit, session.narrative
    if audit is None:
        return [], ""
    out: list[AnomalyAlert] = []

    def alert(sev: Severity, col: str, title: str, desc: str, todo: str) -> None:
        out.append(AnomalyAlert(title=title, severity=sev, description=desc, affected_metric=col,
                                suggested_investigation=todo))

    for d in audit.decisions:
        name = _name(d.column, narrative)
        if d.operation == "keep" and d.after_null_pct > HIGH_NULL_PCT:
            alert(Severity.CRITICAL if d.after_null_pct > 50 else Severity.HIGH, d.column,
                  f"{name.capitalize()}: {_pct(d.after_null_pct)} missing",
                  f"{_pct(d.after_null_pct)} of {name} values are missing. They are left out of "
                  "every result, not filled in.",
                  f"Check why {name} is often blank at the source.")
        elif d.operation == "type_coerce" and d.after_null_pct - d.before_null_pct > 1:
            alert(Severity.MEDIUM, d.column, f"{name.capitalize()}: unreadable values",
                  f"After reading the values, {_pct(d.after_null_pct)} of {name} is missing; the "
                  "values that could not be read are left out of every result.",
                  f"Fix the {name} entries that are not valid values at the source.")
        elif d.operation == "fill_unknown" and d.before_null_pct > 5:
            alert(Severity.MEDIUM if d.before_null_pct > 20 else Severity.LOW, d.column,
                  f"{name.capitalize()}: missing labels grouped",
                  f"{_pct(d.before_null_pct)} of {name} labels were missing and are grouped as "
                  "Unknown.", f"Fill in {name} at the source.")
    report = audit.anomaly_report
    for f in report.flags if report else []:
        name = _name(f.column, narrative)
        if f.heavy_tailed:
            alert(Severity.LOW, f.column, f"{name.capitalize()}: a long tail of large values",
                  f"A few very large {name} values are normal for this data; they were kept.",
                  f"Report the typical {name} alongside the average.")
        else:
            alert(Severity.MEDIUM, f.column, f"{name.capitalize()}: {f.extreme_count} extreme values",
                  f"{f.extreme_count} {name} values ({_pct(f.extreme_pct)} of rows) are far "
                  "outside the usual range. They were kept.",
                  f"Verify the largest {name} values against the source records.")
    if audit.duplicates_removed:
        alert(Severity.LOW, "", f"Duplicates: {audit.duplicates_removed} rows removed",
              f"{audit.duplicates_removed} duplicate records (the same ID twice) were removed "
              "before the analysis.", "Find where duplicate records enter the export.")
    return _compress_alerts(out)


# ── Alert ordering, executive sanitizer, legacy text ───────────────────────────

_SEVERITY_RANK: dict[Severity, int] = {
    Severity.CRITICAL: 4,
    Severity.HIGH: 3,
    Severity.MEDIUM: 2,
    Severity.LOW: 1,
}


def _compress_alerts(alerts: list[AnomalyAlert]) -> tuple[list[AnomalyAlert], str]:
    """Sort by severity descending, keep the top 5, return an overflow note for the rest."""
    if not alerts:
        return [], ""
    ranked = sorted(alerts, key=lambda a: _SEVERITY_RANK.get(a.severity, 0), reverse=True)
    kept = ranked[:5]
    extras = len(ranked) - len(kept)
    note = ""
    if extras > 0:
        plural = "s" if extras != 1 else ""
        note = f"{extras} additional minor issue{plural} detected — see analyst detail tab."
    return kept, note


# Method phrases with a plain equivalent: replaced, so the sentence survives the jargon rule.
_EXECUTIVE_REPLACEMENTS: dict[str, str] = {
    "correlation coefficient": "relationship strength",
    "confidence interval": "uncertainty range",
    "iqr method": "the standard outlier check",
    "z-score method": "the standard outlier check",
}

# Regex to detect raw snake_case / camelCase tokens that look like column names.
_RAW_COL_PATTERN = re.compile(r"\b[a-z][a-z0-9]*(?:_[a-z0-9]+)+\b|\b[a-z]+(?:[A-Z][a-z0-9]+)+\b")


def _clean_for_executive(text: str, narrative: DataNarrative | None) -> str:
    """Executive wording: raw column names → display names (then any snake/camelCase token →
    words), method phrases → plain ones, no backticks. Jargon that's left is a sentence the
    repair removes."""
    if not text:
        return ""
    out = text.replace("`", "")
    # Longest raw name first so 'order_date' wins over 'order'; skip same-word no-ops.
    if narrative and narrative.column_display_names:
        for raw_name, display in sorted(narrative.column_display_names.items(),
                                        key=lambda kv: len(kv[0]), reverse=True):
            if raw_name and raw_name.lower() != display.lower():
                out = re.sub(rf"\b{re.escape(raw_name)}\b", display, out, flags=re.IGNORECASE)
    for needle, replacement in _EXECUTIVE_REPLACEMENTS.items():
        out = re.sub(re.escape(needle), replacement, out, flags=re.IGNORECASE)

    def _humanize(match: re.Match[str]) -> str:
        token = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", match.group(0))
        return re.sub(r"\s+", " ", token.replace("_", " ")).strip().lower()
    out = _RAW_COL_PATTERN.sub(_humanize, out)
    return re.sub(r"\s{2,}", " ", out).strip()


def _flatten_executive_to_text(ev: ExecutiveSummary) -> str:
    """The legacy `executive_summary` string: chat history, embeddings, PPTX export."""
    return " ".join(p for p in [ev.headline, *(c.text for c in ev.paragraphs)] if p).strip()
